-- 1. Evidence Vault Table (Deterministic metadata, SHA-256, Perceptual Hash)
CREATE TABLE IF NOT EXISTS public.evidence_vault (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename TEXT NOT NULL,
    file_type TEXT NOT NULL,
    sha256 TEXT NOT NULL,
    phash TEXT,
    size_bytes BIGINT NOT NULL,
    uploaded_at_utc TEXT NOT NULL,
    vault_path TEXT NOT NULL,
    source_note TEXT,
    duplicate_of_id BIGINT REFERENCES public.evidence_vault(id) ON DELETE SET NULL,
    meta_json JSONB
);

-- 2. Extracted Claims Table (Epistemic claims with extraction method & confidence)
CREATE TABLE IF NOT EXISTS public.extracted_claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidence_id BIGINT NOT NULL REFERENCES public.evidence_vault(id) ON DELETE CASCADE,
    claim_type TEXT NOT NULL, -- date | amount | person | org | location | account | txn_ref | statement
    value TEXT NOT NULL,
    normalized_value TEXT,
    label TEXT NOT NULL, -- VERIFIED_FACT | EXTRACTED_OBSERVATION | TAMPER_INDICATOR | AI_INFERENCE
    location_ref TEXT,
    confidence REAL NOT NULL DEFAULT 1.0,
    method TEXT NOT NULL -- parser | gemini | rapidocr | regex
);

-- 3. Entities Table (Discovered knowledge graph nodes)
CREATE TABLE IF NOT EXISTS public.entities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    type TEXT NOT NULL, -- person | org | location | account | txn_ref
    aliases_json JSONB DEFAULT '[]'::jsonb
);

-- 4. Edges Table (Entity relationship graph supported by claims)
CREATE TABLE IF NOT EXISTS public.edges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_entity_id BIGINT NOT NULL REFERENCES public.entities(id) ON DELETE CASCADE,
    target_entity_id BIGINT NOT NULL REFERENCES public.entities(id) ON DELETE CASCADE,
    relation TEXT NOT NULL,
    evidence_claim_ids_json JSONB DEFAULT '[]'::jsonb,
    label TEXT NOT NULL -- EXTRACTED_OBSERVATION | AI_INFERENCE
);

-- 5. Tamper Flags Table (Structural, forensic, and visual anomalies)
CREATE TABLE IF NOT EXISTS public.tamper_flags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidence_id BIGINT NOT NULL REFERENCES public.evidence_vault(id) ON DELETE CASCADE,
    flag_type TEXT NOT NULL, -- ela_anomaly | pdf_revision | pdf_meta_mismatch | dkim_fail | header_mismatch | duplicate
    detail TEXT NOT NULL,
    region_json JSONB,
    score REAL NOT NULL DEFAULT 0.0,
    label TEXT NOT NULL DEFAULT 'TAMPER_INDICATOR'
);

-- 6. Contradictions Table (Timeline, amount, and sequence discrepancies)
CREATE TABLE IF NOT EXISTS public.contradictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL, -- sequence_violation | date_conflict | amount_conflict | account_conflict | metadata_vs_content | duplicate_content
    description TEXT NOT NULL,
    claim_a_id BIGINT REFERENCES public.extracted_claims(id) ON DELETE SET NULL,
    claim_b_id BIGINT REFERENCES public.extracted_claims(id) ON DELETE SET NULL,
    severity TEXT NOT NULL, -- low | medium | high
    confidence REAL NOT NULL,
    confidence_reason TEXT NOT NULL,
    narrative TEXT NOT NULL,
    review_status TEXT NOT NULL DEFAULT 'pending', -- pending | accepted | rejected | needs_more_info
    reviewer_note TEXT,
    label TEXT NOT NULL DEFAULT 'TAMPER_INDICATOR'
);

-- 7. Audit Chain Table (Cryptographic SHA-256 hash-chained ledger)
CREATE TABLE IF NOT EXISTS public.audit_chain (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp_utc TEXT NOT NULL,
    actor TEXT NOT NULL, -- system | human
    action TEXT NOT NULL,
    target TEXT NOT NULL,
    detail_json JSONB NOT NULL,
    prev_hash TEXT NOT NULL,
    entry_hash TEXT NOT NULL
);

-- Performance Indexes
CREATE INDEX IF NOT EXISTS idx_claims_evidence ON public.extracted_claims(evidence_id);
CREATE INDEX IF NOT EXISTS idx_tamper_evidence ON public.tamper_flags(evidence_id);
CREATE INDEX IF NOT EXISTS idx_audit_prev_hash ON public.audit_chain(prev_hash);
CREATE INDEX IF NOT EXISTS idx_edges_source ON public.edges(source_entity_id);
CREATE INDEX IF NOT EXISTS idx_edges_target ON public.edges(target_entity_id);
CREATE INDEX IF NOT EXISTS idx_evidence_sha256 ON public.evidence_vault(sha256);

-- Disable Row Level Security (RLS) restrictions for service_role and backend API
ALTER TABLE public.evidence_vault ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.extracted_claims ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.entities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.edges ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tamper_flags ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contradictions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_chain ENABLE ROW LEVEL SECURITY;

