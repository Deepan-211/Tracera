CREATE POLICY "Allow public read-write on extracted_claims" ON public.extracted_claims FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read-write on entities" ON public.entities FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read-write on edges" ON public.edges FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read-write on tamper_flags" ON public.tamper_flags FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read-write on contradictions" ON public.contradictions FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read-write on audit_chain" ON public.audit_chain FOR ALL USING (true) WITH CHECK (true);
